use std::hash::{Hash, Hasher};

use serde::{Deserialize, Serialize};

use super::boundary::CompactionBoundary;

/// Stable identity of one transcript entry within a chat history.
#[derive(Clone, Copy, Debug, PartialEq, Eq, PartialOrd, Ord, Hash, Serialize, Deserialize)]
pub(crate) struct EntryId(u64);

impl EntryId {
    /// Creates an identifier assigned by the agent side.
    pub(crate) const fn new(value: u64) -> Self {
        Self(value)
    }

    /// Returns the numeric value used by storage and deduplication.
    pub(crate) const fn value(self) -> u64 {
        self.0
    }

    /// Derives a stable identity from a provider tool-call id.
    ///
    /// Tool calls and their results share the derived identity, so a result replaces the
    /// matching call block instead of creating a second row. Collisions are possible in
    /// theory but require two distinct provider ids with the same 64-bit hash.
    pub(crate) fn from_call_id(call_id: &str) -> Self {
        let mut hasher = std::collections::hash_map::DefaultHasher::new();
        call_id.hash(&mut hasher);
        Self(hasher.finish())
    }
}

/// One durable item shown in the transcript.
#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]
pub(crate) struct TranscriptEntry {
    /// Stable identity used to replace live projections with canonical entries.
    pub(crate) id: EntryId,
    /// Durable payload and its presentation category.
    pub(crate) kind: TranscriptEntryKind,
}

impl TranscriptEntry {
    /// Creates a durable transcript entry with its assigned identity.
    pub(crate) fn new(id: EntryId, kind: TranscriptEntryKind) -> Self {
        Self { id, kind }
    }
}

/// Durable transcript entry categories.
#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]
pub(crate) enum TranscriptEntryKind {
    /// A user prompt, including prompts generated by application workflows.
    User {
        /// Exact prompt text.
        text: String,
    },
    /// An accepted assistant answer with optional reasoning.
    Assistant {
        /// Final answer text.
        text: String,
        /// Reasoning content retained for the collapsed reasoning block.
        reasoning: Option<String>,
    },
    /// A tool call requested by the model.
    ToolCall {
        /// Provider tool-call identifier used to pair the result.
        call_id: String,
        /// Exact runtime tool name.
        tool_name: String,
        /// Complete tool arguments for pretty-printed JSON display.
        arguments: serde_json::Value,
    },
    /// A tool result returned to the model.
    ToolResult {
        /// Provider tool-call identifier of the paired call.
        call_id: String,
        /// Exact runtime tool name.
        tool_name: String,
        /// Complete result payload formatted for display without truncation.
        output: String,
        /// Whether the tool reported an actionable failure.
        failed: bool,
    },
    /// A compaction summary that became the active model context.
    Summary {
        /// Exact summary text produced by the summarizer.
        text: String,
    },
    /// A boundary that separates archived history from the active context.
    Boundary(CompactionBoundary),
}

#[cfg(test)]
mod tests {
    use super::{EntryId, TranscriptEntry, TranscriptEntryKind};
    use crate::entities::transcript::boundary::CompactionBoundary;

    #[test]
    fn entry_ids_order_by_their_numeric_value() {
        assert!(EntryId::new(1) < EntryId::new(2));
        assert_eq!(EntryId::new(42).value(), 42);
    }

    #[test]
    fn call_ids_map_to_the_same_identity_for_calls_and_results() {
        assert_eq!(
            EntryId::from_call_id("call-1"),
            EntryId::from_call_id("call-1")
        );
        assert_ne!(
            EntryId::from_call_id("call-1"),
            EntryId::from_call_id("call-2")
        );
    }

    #[test]
    fn every_entry_kind_round_trips_through_json() -> anyhow::Result<()> {
        let entries = [
            TranscriptEntry::new(
                EntryId::new(1),
                TranscriptEntryKind::User {
                    text: "hello".to_string(),
                },
            ),
            TranscriptEntry::new(
                EntryId::new(2),
                TranscriptEntryKind::Assistant {
                    text: "hi".to_string(),
                    reasoning: Some("thought".to_string()),
                },
            ),
            TranscriptEntry::new(
                EntryId::new(3),
                TranscriptEntryKind::ToolCall {
                    call_id: "call-1".to_string(),
                    tool_name: "read_file".to_string(),
                    arguments: serde_json::json!({"path": "src/main.rs"}),
                },
            ),
            TranscriptEntry::new(
                EntryId::new(4),
                TranscriptEntryKind::ToolResult {
                    call_id: "call-1".to_string(),
                    tool_name: "read_file".to_string(),
                    output: "contents".to_string(),
                    failed: false,
                },
            ),
            TranscriptEntry::new(
                EntryId::new(5),
                TranscriptEntryKind::Summary {
                    text: "summary".to_string(),
                },
            ),
            TranscriptEntry::new(
                EntryId::new(6),
                TranscriptEntryKind::Boundary(CompactionBoundary::new("chat.0.jsonl")),
            ),
        ];

        for entry in entries {
            let json = serde_json::to_value(&entry)?;
            let restored: TranscriptEntry = serde_json::from_value(json)?;
            assert_eq!(restored, entry);
        }
        Ok(())
    }
}
